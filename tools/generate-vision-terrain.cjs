#!/usr/bin/env node
'use strict';
// Extract the unchanged game cell flags, not the converter's implementation.
// Format reference: https://github.com/FrankTheBoxMonster/LoL-NGRID-converter
// Usage: node tools/generate-vision-terrain.cjs [path/to/AIPath_SRX_3.aimesh_ngrid]
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const dns = require('node:dns');
const COMMIT = '92943ed2b2d5e82c86d680e69f53f247c89aefee';
const SOURCE_PATH = 'SR_2024/navgrids/Base/AIPath_SRX_3.aimesh_ngrid';
const SOURCE_URL = 'https://raw.githubusercontent.com/FrankTheBoxMonster/LoL-NGRID-converter/' + COMMIT + '/' + SOURCE_PATH;
const SOURCE_BLOB = 'f1b6f33efe26e778df25317cee1e6bfd46e1c4cc';
const ART_BLOB = '3fc3bf357b74fe4b3ae46145fc75d7ecf2675ec1';
function blobHash(bytes) {
  return crypto.createHash('sha1').update('blob ' + bytes.length + '\0').update(bytes).digest('hex');
}
async function main() {
  dns.setDefaultResultOrder('ipv4first');
  let bytes;
  if (process.argv[2]) bytes = fs.readFileSync(process.argv[2]);
  else {
    const response = await fetch(SOURCE_URL);
    if (!response.ok) throw new Error('Navgrid download failed: ' + response.status);
    bytes = Buffer.from(await response.arrayBuffer());
  }
  if (blobHash(bytes) !== SOURCE_BLOB) throw new Error('Unexpected source bytes; review the dataset before updating it.');
  if (bytes.readUInt8(0) !== 7 || bytes.readUInt16LE(1) !== 1) throw new Error('Unsupported navgrid version.');
  const width = bytes.readUInt32LE(31), height = bytes.readUInt32LE(35), cellSize = bytes.readFloatLE(27);
  if (width !== 295 || height !== 296 || cellSize !== 50) throw new Error('Unexpected map dimensions.');
  const count = width * height, flagOffset = 39 + count * 48;
  if (flagOffset + count * 2 > bytes.length) throw new Error('Truncated navgrid.');
  const flags = [];
  // The original cells are X-right / Z-up. The planner uses X-right / Y-down.
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    const flag = bytes.readUInt16LE(flagOffset + ((height - 1 - y) * width + x) * 2);
    if (flag & ~0x1dc7) throw new Error('Unexpected flag bits: ' + flag);
    flags.push(flag);
  }
  const runs = [];
  for (let i = 0; i < count;) {
    let end = i + 1;
    while (end < count && flags[end] === flags[i]) end++;
    runs.push(end - i, flags[i]); i = end;
  }
  const metadata = {
    id: 'summoners-rift-2024-base', label: '2024 base Rift', width, height, cellSize, mapUnits: 15000,
    mapBounds: {left: 10 / 1024 * 100, top: (1016.25 / 1024 - height / 300) * 100, width: width / 3, height: height / 3},
    worldBounds: {minX: bytes.readFloatLE(3), minZ: bytes.readFloatLE(11), maxX: bytes.readFloatLE(15), maxZ: bytes.readFloatLE(23)},
    bits: {brush: 1, wall: 2, structureWall: 4, transparentWall: 64, unknown128: 128, alwaysVisible: 256, blueOnly: 1024, redOnly: 2048, gate: 4096},
    source: {url: SOURCE_URL, repository: 'https://github.com/FrankTheBoxMonster/LoL-NGRID-converter', commit: COMMIT, path: SOURCE_PATH, gitBlob: SOURCE_BLOB, sha256: crypto.createHash('sha256').update(bytes).digest('hex'), navgridVersion: '7.1', artworkPath: 'SR_2024/renders/Base.png', artworkGitBlob: ART_BLOB, overlayPath: 'SR_2024/render_navgrids/Base.png'},
    alignment: {method: 'Uniform 15000-unit orthographic span; image offset registered against the matching author navgrid overlay at 1024 pixels.', approximate: true, estimatedErrorUnits: 10},
    limitations: ['2024 base terrain; later map changes and elemental variants are not included.', 'Image registration is measured, not an official Riot world-to-image transform.', 'Contains static cell flags only; game vision timing and ability effects are separate.']
  };
  const rows = [];
  for (let i = 0; i < runs.length; i += 120) rows.push('    ' + runs.slice(i, i + 120).join(','));
  const output = '// Generated by tools/generate-vision-terrain.cjs; do not hand-edit.\n' +
    '// Riot Games terrain data mirrored by FrankTheBoxMonster; see source metadata below.\n' +
    '(function (root) {\n  \'use strict\';\n  const terrain = ' + JSON.stringify(metadata, null, 2).replace(/\n/g, '\n  ') + ';\n' +
    '  const runs = [\n' + rows.join(',\n') + '\n  ];\n' +
    '  const flags = new Uint16Array(terrain.width * terrain.height);\n  let offset = 0;\n' +
    '  for (let i = 0; i < runs.length; i += 2) {\n    flags.fill(runs[i + 1], offset, offset + runs[i]);\n    offset += runs[i];\n  }\n' +
    '  if (offset !== flags.length) throw new Error(\'Invalid vision terrain data.\');\n' +
    '  terrain.flags = flags;\n  root.VISION_TERRAIN = terrain;\n' +
    '  if (typeof module === \'object\' && module.exports) module.exports = terrain;\n' +
    '})(typeof globalThis !== \'undefined\' ? globalThis : this);\n';
  const destination = path.join(__dirname, '..', 'assets', 'vision-terrain.js');
  fs.writeFileSync(destination, output);
  console.log('Generated ' + count + ' unchanged cell flags (' + Buffer.byteLength(output) + ' bytes) at ' + destination);
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
